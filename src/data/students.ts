export function parseStudentsFromCsv(csv: string): Student[] {
  const lines = csv.trim().split('\n');
  const students: Student[] = [];
  
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split(',');
    if (parts.length >= 3) {
      const sekolah = parts[0].trim();
      const kelas = parts[1].trim();
      const nama = parts[2].trim();
      // Generate clean unique ID
      const id = `${kelas.replace(/\s+/g, '_')}_${nama.replace(/[^a-zA-Z0-9]/g, '_')}`.toLowerCase();
      students.push({ id, sekolah, kelas, nama });
    }
  }
  return students;
}

